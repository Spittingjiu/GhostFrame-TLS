// Config is the on-disk server configuration (/etc/gft/server.json, mode 0600).
type Config struct {
	Listen     string `json:"listen"`
	PublicHost string `json:"public_host"`
	SNI        string `json:"sni"`
	PSK        string `json:"psk"` // base64
	CertFile   string `json:"cert_file"`
	KeyFile    string `json:"key_file"`
	PanelPath  string `json:"panel_path"` // e.g. /gft-panel-xxxxxxxx
	PanelHash  string `json:"panel_hash"` // bcrypt
	Pin        string `json:"pin"`
	StateDir   string `json:"state_dir"`
}

func LoadConfig(path string) (*Config, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var c Config
	if err := json.Unmarshal(b, &c); err != nil {
		return nil, err
	}
	if c.Listen == "" || c.PSK == "" || c.PanelPath == "" || c.PanelHash == "" {
		return nil, errors.New("incomplete config")
	}
	return &c, nil
}

// Secrets are generated by Init and printed exactly once.
type Secrets struct {
	Host          string `json:"host"`
	Port          int    `json:"port"`
	SNI           string `json:"sni"`
	PSK           string `json:"psk"`
	Pin           string `json:"pin"`
	PanelPath     string `json:"panel_path"`
	PanelPassword string `json:"panel_password"`
	Link          string `json:"link"`
	Created       bool   `json:"created"` // false = existing config kept (password not shown)
}

func randString(n int, alphabet string) string {
	out := make([]byte, n)
	max := big.NewInt(int64(len(alphabet)))
	for i := range out {
		v, _ := rand.Int(rand.Reader, max)
		out[i] = alphabet[v.Int64()]
	}
	return string(out)
}

// Init idempotently generates certificate, PSK, panel path and password.
// If a config already exists it is kept and Secrets.Created=false.
func Init(confDir, stateDir, host, sni, listen string) (*Secrets, error) {
	cfgPath := filepath.Join(confDir, "server.json")
	if c, err := LoadConfig(cfgPath); err == nil {
		return secretsFrom(c, "", false), nil
	}
	if err := os.MkdirAll(confDir, 0o750); err != nil {
		return nil, err
	}
	if err := os.MkdirAll(stateDir, 0o750); err != nil {
		return nil, err
	}
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return nil, err
	}
	serial, _ := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 120))
	tmpl := &x509.Certificate{
		SerialNumber: serial,
		Subject:      pkix.Name{CommonName: sni},
		DNSNames:     []string{sni},
		NotBefore:    time.Now().Add(-time.Hour),
		NotAfter:     time.Now().AddDate(10, 0, 0),
		KeyUsage:     x509.KeyUsageDigitalSignature,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}
	if ip := net.ParseIP(host); ip != nil {
		tmpl.IPAddresses = []net.IP{ip}
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
	if err != nil {
		return nil, err
	}
	kb, _ := x509.MarshalECPrivateKey(key)
	certFile, keyFile := filepath.Join(confDir, "cert.pem"), filepath.Join(confDir, "key.pem")
	if err := os.WriteFile(certFile, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), 0o644); err != nil {
		return nil, err
	}
	if err := os.WriteFile(keyFile, pem.EncodeToMemory(&pem.Block{Type: "EC PRIVATE KEY", Bytes: kb}), 0o600); err != nil {
		return nil, err
	}
	psk := make([]byte, 32)
	_, _ = rand.Read(psk)
	pass := randString(20, "abcdefghjkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789")
	hash, err := bcrypt.GenerateFromPassword([]byte(pass), 12)
	if err != nil {
		return nil, err
	}
	sum := sha256.Sum256(der)
	c := &Config{
		Listen: listen, PublicHost: host, SNI: sni,
		PSK:      base64.StdEncoding.EncodeToString(psk),
		CertFile: certFile, KeyFile: keyFile,
		PanelPath: "/gft-panel-" + randString(32, "abcdefghijklmnopqrstuvwxyz0123456789"),
		PanelHash: string(hash), Pin: hex.EncodeToString(sum[:]), StateDir: stateDir,
	}
	b, _ := json.MarshalIndent(c, "", "  ")
	if err := os.WriteFile(cfgPath, b, 0o600); err != nil {
		return nil, err
	}
	return secretsFrom(c, pass, true), nil
}

func listenPort(listen string) int {
	_, ps, err := net.SplitHostPort(listen)
	if err != nil {
		return 443
	}
	p, _ := strconv.Atoi(ps)
	return p
}

func (c *Config) Link(p gft.Params) *gft.Link {
	port := listenPort(c.Listen)
	return &gft.Link{V: 1, Host: c.PublicHost, Port: port, SNI: c.SNI, PSK: c.PSK, Pin: c.Pin, Params: &p, Remark: "GhostFrame-JP"}
}

func secretsFrom(c *Config, pass string, created bool) *Secrets {
	l := c.Link(gft.DefaultParams())
	return &Secrets{Host: c.PublicHost, Port: listenPort(c.Listen), SNI: c.SNI, PSK: c.PSK, Pin: c.Pin,
		PanelPath: c.PanelPath, PanelPassword: pass, Link: l.Encode(), Created: created}
}
